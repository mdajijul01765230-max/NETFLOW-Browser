/**
 * Creates a recursive proxy that provides fallback values:
 * 1. If a key is missing or undefined in target, it looks it up in fallback.
 * 2. If it's missing in both, it safely returns an empty string instead of undefined.
 * 3. Any nested object is wrapped so chain accesses never throw TypeError.
 */
function createFallbackProxy<T extends object>(target: T, fallback?: any): T {
  return new Proxy(target || ({} as T), {
    get(obj: any, prop: string | symbol) {
      if (typeof prop === "symbol") return obj[prop];
      if (prop === "toJSON") return () => target;
      if (prop === "toString" || prop === "valueOf") return () => "";

      const val = obj[prop];
      const fallbackVal = fallback ? fallback[prop] : undefined;
      const activeVal = val !== undefined && val !== null ? val : fallbackVal;

      if (activeVal !== undefined && activeVal !== null) {
        if (typeof activeVal === "object" && !Array.isArray(activeVal)) {
          return createFallbackProxy(
            val && typeof val === "object" ? val : {},
            fallbackVal && typeof fallbackVal === "object" ? fallbackVal : {}
          );
        }
        return activeVal;
      }

      return "";
    },
  });
}

const safeBn = createFallbackProxy(rawTranslations.bn, rawTranslations.en);
const safeEn = createFallbackProxy(rawTranslations.en, rawTranslations.bn);

export const translations = new Proxy(
  { bn: safeBn, en: safeEn },
  {
    get(target: any, prop: string | symbol) {
      if (prop === "en") return target.en;
      if (prop === "bn") return target.bn;
      if (typeof prop === "string") return target.bn;
      return target[prop];
    },
  }
) as typeof rawTranslations;

